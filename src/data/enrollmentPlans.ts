export function filterLocalEnrollmentPlans(options: {
  provinceName: string;
  schoolName?: string;
  schoolUuid?: string;
  majorKeyword?: string;
}): EnrollmentPlan[] {
  return localEnrollmentPlans.filter((plan) => {
    const hasSchoolFilter = Boolean(options.schoolName || options.schoolUuid);
    if (!hasSchoolFilter && plan.provinceName !== options.provinceName) {
      return false;
    }
    if (options.schoolUuid && plan.schoolUuid !== options.schoolUuid) {
      return false;
    }
    if (options.schoolName) {
      const keyword = options.schoolName.trim();
      if (
        !plan.schoolName.includes(keyword) &&
        !keyword.includes(plan.schoolName.replace(/大学|学院/g, ""))
      ) {
        return false;
      }
    }
    if (
      options.majorKeyword &&
      !plan.majorName.includes(options.majorKeyword) &&
      !plan.shortMajorName.includes(options.majorKeyword)
    ) {
      return false;
    }
    return true;
  });
}
