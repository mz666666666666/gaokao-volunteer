def main() -> None:
    lines = [
        'import type { University } from "../types";',
        "import { GAOKAO_DATA_YEAR } from \"../constants/gaokao\";",
        "",
        "type RawCollege = [id: string, name: string, province: string, city: string, level: University[\"level\"]];",
        "",
        "const rawNationalColleges: RawCollege[] = " + json.dumps(COLLEGES, ensure_ascii=False, indent=2) + ";",
        "",
        "const defaultMajors = [\"计算机科学与技术\", \"软件工程\", \"会计学\"];",
        "",
        "function estimateScore(level: University[\"level\"]): number {",
        "  switch (level) {",
        "    case \"985\": return 640;",
        "    case \"211\": return 590;",
        "    case \"双一流\": return 580;",
        "    case \"专科\": return 420;",
        "    default: return 520;",
        "  }",
        "}",
        "",
        "function estimateRank(level: University[\"level\"]): number {",
        "  switch (level) {",
        "    case \"985\": return 8000;",
        "    case \"211\": return 35000;",
        "    case \"双一流\": return 42000;",
        "    case \"专科\": return 180000;",
        "    default: return 75000;",
        "  }",
        "}",
        "",
        "/** 全国院校搜索索引（自动生成，覆盖31省） */",
        "export const nationalColleges: University[] = rawNationalColleges.map(([id, name, province, city, level]) => ({",
        "  id,",
        "  name,",
        "  province,",
        "  city,",
        "  level,",
        "  batchLevel: level === \"专科\" ? \"专科\" : \"本科\",",
        "  year: GAOKAO_DATA_YEAR,",
        "  minScore: estimateScore(level),",
        "  minRank: estimateRank(level),",
        "  hotMajors: defaultMajors,",
        "  dataSource: \"local\" as const,",
        "}));",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {len(COLLEGES)} colleges -> {OUT}")


